import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const CONTENT_DIR = 'src/content';
const OUTPUT = join(CONTENT_DIR, 'bodies.ts');

export function policyKeysFromManifest(source) {
  return [...source.matchAll(/\{\s*key:\s*'([^']+)',\s*title:\s*'[^']+'\s*\}/g)].map(
    ([, key]) => key,
  );
}

export function renderPolicyBodies(entries) {
  const body = entries
    .map(([key, markdown]) => `  ${key}: ${JSON.stringify(markdown)},`)
    .join('\n');
  return `// Generated by scripts/sync-policy-bodies.mjs from the Markdown policy sources.\n` +
    `// Do not edit this file directly.\n` +
    `import type { DocKey } from './manifest';\n\n` +
    `export const POLICY_BODIES: Record<DocKey, string> = {\n${body}\n};\n`;
}

export function readPolicyEntries() {
  const manifest = readFileSync(join(CONTENT_DIR, 'manifest.ts'), 'utf8');
  return policyKeysFromManifest(manifest).map((key) => [
    key,
    readFileSync(join(CONTENT_DIR, `${key}.md`), 'utf8'),
  ]);
}

export function syncPolicyBodies() {
  writeFileSync(OUTPUT, renderPolicyBodies(readPolicyEntries()));
}

if (import.meta.url === `file://${process.argv[1]}`) syncPolicyBodies();
