import { readFileSync, writeFileSync } from 'node:fs';

// The Edge bundler requires local .ts imports. Keep the tested source authoritative.
for (const name of ['handle', 'prompt', 'validate', 'endpoint', 'availability']) {
  const source = `src/features/recommend/chat/${name}.ts`;
  const text = readFileSync(source, 'utf8').replace(/from '(\.\/[^']+)'/g, "from '$1.ts'");
  writeFileSync(`supabase/functions/_shared/recommend/${name}.ts`, `// SOURCE OF TRUTH: ${source}. Generated by scripts/sync-routine-chat.mjs.\n${text}`);
}
