import { act, cleanup, fireEvent, render } from '@testing-library/react-native';
import { AppState, type AppStateStatus } from 'react-native';
import type { CatalogueSnapshot } from '../../../catalog/state';
const mockLoad=jest.fn();
let mockCatalogue: CatalogueSnapshot;
const mockShop={products:[],cart:null,loadingProducts:false,error:null as string|null,catalogStatus:'live',catalogUpdatedAt:null};
jest.mock('../shop-privacy',()=>({hasAcceptedShopPrivacy:()=>true}));
jest.mock('../../../match/product-catalog',()=>({catalogueIsDemo:false,useProductCatalogue:()=>mockCatalogue,refreshCatalogue:jest.fn()}));
jest.mock('../shopify-store',()=>({useShopifyStore:()=>mockShop,shopifyStore:{loadProducts:(...args:unknown[])=>mockLoad(...args)}}));
import { ShopifyShopScreen } from '../ui/ShopifyShopScreen';
const props={onOpen:jest.fn(),onBag:jest.fn(),onDecline:jest.fn()};
beforeEach(()=>{mockLoad.mockClear();mockCatalogue={status:'ready',products:[],previousProducts:[]};mockShop.loadingProducts=false;mockShop.error=null;});
afterEach(async()=>{await cleanup();jest.useRealTimers();jest.restoreAllMocks();});
test('refreshes on foreground and bounded timer and removes subscriptions',async()=>{
  jest.useFakeTimers();
  const remove=jest.fn();
  let foreground: (state: AppStateStatus)=>void=()=>{};
  jest.spyOn(AppState,'addEventListener').mockImplementation((_event,callback)=>{foreground=callback;return {remove};});
  const view=await render(<ShopifyShopScreen {...props} />);
  mockLoad.mockClear();
  await act(async()=>{jest.advanceTimersByTime(60_000);});
  expect(mockLoad).toHaveBeenCalledWith(true);
  mockLoad.mockClear();
  await act(async()=>{foreground('active');});
  expect(mockLoad).toHaveBeenCalledWith(true);
  await view.unmount();
  expect(remove).toHaveBeenCalled();
});
test('refreshes on same-ID catalogue price revision',async()=>{
  const {catalog}=jest.requireActual('../../../match/demo-product-catalog');
  mockCatalogue={status:'ready',products:[catalog[0]],previousProducts:[]};
  const view=await render(<ShopifyShopScreen {...props} />);
  mockLoad.mockClear();
  mockCatalogue={...mockCatalogue,products:[{...catalog[0],price:99}]};
  await view.rerender(<ShopifyShopScreen {...props} />);
  expect(mockLoad).toHaveBeenCalledWith(true);
});
test('combined offline catalogue and Shopify loading has one glass state and no retry while loading',async()=>{
  mockCatalogue={status:'offline',products:[],previousProducts:[]};mockShop.loadingProducts=true;mockShop.error='Unavailable';
  const view=await render(<ShopifyShopScreen {...props} />);
  expect(view.getAllByTestId('catalogue-notice')).toHaveLength(1);
  expect(view.queryByRole('button',{name:'Try again'})).toBeNull();
  expect(view.queryByText('Shop unavailable')).toBeNull();
  mockShop.loadingProducts=false;
  await view.rerender(<ShopifyShopScreen {...props} />);
  expect(view.getAllByRole('button',{name:'Try again'})).toHaveLength(1);
  mockLoad.mockClear();
  await fireEvent.press(view.getByRole('button',{name:'Try again'}));
  expect(mockLoad).toHaveBeenCalledTimes(1);
  expect(mockLoad).toHaveBeenCalledWith(true);
});
